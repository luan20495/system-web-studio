// -------------------------------------------------------------------------------------------------------------- routing / 404
/** the one UPDATE_SITE for the 404 page (builder panel and Website drawer, M-047): empty fields fall back to the default text */
export function opsSetNotFound(title: string, message: string): { ops: SchemaOperation[]; summary: string } {
  return { ops: [{ type: "UPDATE_SITE", props: { notFound: { ...(title.trim() ? { title: title.trim() } : {}), ...(message.trim() ? { message: message.trim() } : {}) } } }], summary: "Cập nhật trang 404" };
}

export type RouteResult = { kind: "page"; page: PageNode } | { kind: "notfound"; title: string; message: string };

/** Resolves a public path the way the published site does: "/" = home, "/slug/" = page, anything else = the 404 page of the site. */
export function resolveRoute(schema: PageSchema, path: string): RouteResult {
  const clean = path.split(/[?#]/)[0].replace(/\/+$/, "").replace(/^\/+/, "");
  const pages = listPages(schema);
  const hit = pages.find((p) => p.slug === clean);
  if (hit) return { kind: "page", page: hit };
  const nf = schema.site?.notFound;
  return { kind: "notfound", title: nf?.title || "Không tìm thấy trang", message: nf?.message || "Trang bạn tìm không tồn tại hoặc đã được chuyển đi." };
}

/** Where a NAVIGATE action / menu link with this page id leads: a page, or nowhere (broken). */
export function pageExists(schema: PageSchema, pageId: string): boolean {
  return pageId === HOME_ID || !!schema.pages?.some((p) => p.id === pageId);
}

/** anchors the renderer emits per component type (lib/schema-preview.ts); a menu anchor needs a section that provides it on the page it is shown on */
export const ANCHOR_OF_TYPE: Readonly<Record<string, string>> = {
  Hero: "#top", ProductGrid: "#products", TechnologySection: "#technology", ComparisonBlock: "#comparison", Testimonials: "#testimonials", ContactForm: "#contact",
};
export function anchorsOnPage(sections: Section[]): Set<string> {
  return new Set(sections.map((s) => ANCHOR_OF_TYPE[s.type]).filter((a): a is string => !!a));
}
